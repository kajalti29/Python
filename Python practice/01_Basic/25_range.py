# Range():-👉 range() ek function hai jo numbers ki series (sequence) banata hai.
# Ye mostly loops me use hota hai jahan hume ek specific range tak iterate karna hota hai.

for i in range(5):
    print(i)
# Output:
# 0 
# 1
# 2
# 3
# 4
# Yahan range(5) 0 se start hoke 5 se pehle tak ke numbers generate karta hai, yani 0 se 4 tak.