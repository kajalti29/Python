# 👉 Tuple ek ordered collection of items hota hai, jo (parentheses) brackets ( ) me likha jata hai.
# Ye Immutable hote hain yani inhe change nahi kiya ja sakta.

numbers = (10, 20, 30, 40)
names = ("Kajal", "Riya", "Neha")
mixed = (10, "hello", 3.14, True)
print(numbers)  # Output: (10, 20, 30, 40)
print(names)    # Output: ('Kajal', 'Riya', 'Neha') 
print(mixed)    # Output: (10, 'hello', 3.14, True)