# Function :- Function ek block of code hota hai jo specific task perform karta hai.

# Function ko define karne ke liye 'def' keyword ka use kiya jata hai.
def greet():
    print("Hello, welcome to Python functions!")
# Function ko call karne ke liye uska naam likhna hota hai followed by parentheses.
greet()  # Output: Hello, welcome to Python functions!



# Function with Parameters:- Function me parameters pass karke hum uske behavior ko customize kar sakte hain.
def add(a, b):
    print(a + b)

add(10, 5)
# Output: 15
