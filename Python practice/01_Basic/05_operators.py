# Arithmetic Operators
a = 10
b = 3
print("Addition:", a + b)          # Output: 13
print("Subtraction:", a - b)       # Output: 7  
print("Multiplication:", a * b)    # Output: 30
print("Division:", a / b)          # Output: 3.3333333333333335
print("Floor Division:", a // b)   # Output: 3  
print("Modulus:", a % b)           # Output: 1
print("Exponentiation:", a ** b)   # Output: 1000

# Comparison Operators
x = 5
y = 10
print("Equal:", x == y)            # Output: False
print("Not Equal:", x != y)        # Output: True
print("Greater Than:", x > y)      # Output: False
print("Less Than:", x < y)         # Output: True
print("Greater Than or Equal:", x >= y)  # Output: False
print("Less Than or Equal:", x <= y)     # Output: True

# Logical Operators
p = True
q = False
print("AND:", p and q)             # Output: False  
print("OR:", p or q)               # Output: True
print("NOT p:", not p)             # Output: False
print("NOT q:", not q)             # Output: True

# Assignment Operators
num = 10
print("Initial Value:", num)        # Output: 10
num += 5
print("After += 5:", num)           # Output: 15
num -= 3
print("After -= 3:", num)           # Output: 12
num *= 2
print("After *= 2:", num)           # Output: 24
num /= 4
print("After /= 4:", num)           # Output: 6.0
num //= 2
print("After //= 2:", num)          # Output: 3.0
num %= 2
print("After %= 2:", num)           # Output: 1.0
num **= 3
print("After **= 3:", num)          # Output: 1.0

# Bitwise Operators
m = 5      # Binary: 0101
n = 3      # Binary: 0011
print("Bitwise AND:", m & n)        # Output: 1 (Binary: 0001)
print("Bitwise OR:", m | n)         # Output: 7 (Binary: 0111)
print("Bitwise XOR:", m ^ n)        # Output: 6 (Binary: 0110)          
print("Bitwise NOT m:", ~m)         # Output: -6 (Binary: ...1010)
print("Left Shift m by 1:", m << 1) # Output: 10 (Binary: 1010)
print("Right Shift m by 1:", m >> 1)# Output: 2 (Binary: 0010)

# Membership Operators
my_list = [1, 2, 3, 4, 5]   
print("3 in my_list:", 3 in my_list)        # Output: True
print("6 not in my_list:", 6 not in my_list) # Output: True 



