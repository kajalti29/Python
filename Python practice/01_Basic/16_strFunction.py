# String Function :- str() function kisi bhi value ko STRING (text) me convert karta hai.

name = input("Enter your name: ")
age = int(input("Enter your age: "))

print("Hello " + name + ", you are " + str(age) + " years old.")
# Yahan str(age) use kiya gaya hai taaki age jo ek integer hai, use string me convert karke concatenate kiya ja sake.