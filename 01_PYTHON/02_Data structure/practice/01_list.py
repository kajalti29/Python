# CREATE A LIST 
cities = ["Indore", "Bhopal", "Ujjain"]
print(cities)


# INDEXing 
cities = ["Indore", "Bhopal", "Ujjain"]
print(cities[0])
print(cities[2])

# NEGATIVE INDEX 
cities = ["Indore", "Bhopal", "Ujjain"]
print(cities[-2])

# Slicing 
cities = ["Indore", "Bhopal", "Ujjain", "Betul", "Devash"]
print(cities[2:4])

# append
cities = ["Indore", "Bhopal", "Ujjain"]
cities.append("Betul")
print(cities)

# pop 
numbers = ["A", "B", "C", "D"]
numbers.pop(2)
print(numbers)

# REMOVE 
numbers = ["A", "B", "C", "D"]
numbers.remove("D")
print(numbers)

# INSER 
numbers = ["A", "B", "C", "D"]
numbers.insert(5, "kaju")
print(numbers)

